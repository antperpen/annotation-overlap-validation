"""
Draws, on a layer of a WSI, the regions annotated by the pathologist (red) and the patches that
cover them (blue), from the partition cache already generated by
validation.patchExtractor_strong_valme.CSVTestListExtractor (file
wsi_patch_map_{dataset}_{overlap}_patch{patch}_stride{stride}.pkl, stored next to the XML). It
does not recompute the partition: it only reads that cache (raw_ROI and covered_ROI) and the WSI,
and draws the rectangle that encloses all the ROIs of the image.

Usage (from the root of the project):
    python3 utils/roi_patch_overlay.py <wsi.tif> <wsi_patch_map_*.pkl> <output.png> \
        [--level N] [--padding PX] [--roi-thickness PX] [--patch-thickness PX] \
        [--full | --crop X0 Y0 X1 Y1] [--allow-large]

--full draws the whole image (complete layer 0 at the given layer) instead of cropping around the
ROIs. --crop X0 Y0 X1 Y1 manually crops those layer 0 coordinates, to keep only one group of ROIs
when they are spread over separate areas of the image. In low layers (0-2) or with large crops
this can mean billions of pixels: by default the script refuses to generate more than MAX_PIXELS
and suggests a higher layer; --allow-large allows it anyway, assuming the required time/memory.

Example with the VALME data:
    python3 utils/roi_patch_overlay.py \
        /path/EXT/VALME/B16-004297-A3.tif \
        /path/EXT/VALME/wsi_patch_map_Valme_1_patch750_stride750.pkl \
        output.png --level 1
"""
import argparse
import os
import pickle
import re

import cv2
import numpy as np
import openslide

ROI_COLOR = (0, 0, 255)     # red (BGR): region annotated by the pathologist (raw_ROI)
PATCH_COLOR = (255, 0, 0)   # blue (BGR): patches that cover that region (covered_ROI)
MAX_PIXELS = 150_000_000    # default limit (~150 megapixels, about 450 MB in RGB) before requiring --allow-large


def parse_patch_size(pkl_path):
    """Extracts the patch footprint (patch_size) from the name of the cache: ..._patch{N}_stride{M}.pkl"""
    match = re.search(r'_patch(\d+)_stride(\d+)\.pkl$', os.path.basename(pkl_path))
    if not match:
        raise ValueError("The name of the cache does not follow the pattern wsi_patch_map_..._patch{N}_stride{M}.pkl: "
                         + pkl_path)
    return int(match.group(1)), int(match.group(2))


def load_entry(pkl_path, wsi_path):
    """Loads from the cache the entry of an image (raw_ROI, covered_ROI, patch_number, etc.)"""
    with open(pkl_path, 'rb') as pkl_file:
        wsi_patch_map = pickle.load(pkl_file)
    key = os.path.splitext(os.path.basename(wsi_path))[0]
    if key not in wsi_patch_map:
        raise KeyError(f"'{key}' is not in the cache {pkl_path}. Available images: {sorted(wsi_patch_map)}")
    return wsi_patch_map[key]


def roi_bounds(entry, padding):
    """Rectangle in layer 0 coordinates that encloses all the annotated ROIs, with a margin"""
    xs0 = [polygon.bounds[0] for polygon, _grade in entry['raw_ROI']]
    ys0 = [polygon.bounds[1] for polygon, _grade in entry['raw_ROI']]
    xs1 = [polygon.bounds[2] for polygon, _grade in entry['raw_ROI']]
    ys1 = [polygon.bounds[3] for polygon, _grade in entry['raw_ROI']]
    return (int(min(xs0)) - padding, int(min(ys0)) - padding,
            int(max(xs1)) + padding, int(max(ys1)) + padding)


def check_size(size, allow_large):
    """Prevents generating an unmanageable image (billions of pixels) unless explicitly requested"""
    width, height = size
    num_pixels = width * height
    if num_pixels > MAX_PIXELS and not allow_large:
        raise ValueError(
            f"The resulting image would be {width}x{height} px ({num_pixels / 1e6:.0f} megapixels, "
            f"~{num_pixels * 3 / 1e9:.1f} GB in RGB): it is not generated so as not to exhaust memory/disk or create "
            "a file that cannot be opened. Use a higher layer (more downsample) or pass --allow-large "
            "if you really want this resolution.")


def draw_overlay(wsi_path, entry, patch_size, level, crop_box, output_path, roi_thickness, patch_thickness,
                 allow_large=False):
    """
    Reads crop_box (layer 0 coordinates) at the given layer and draws on top of it, without
    recomputing anything, the ROIs of the cache in red and the patches that cover them in blue
    """
    slide = openslide.OpenSlide(wsi_path)
    downsample = slide.level_downsamples[level]
    x0, y0, x1, y1 = crop_box
    size = (max(1, int((x1 - x0) / downsample)), max(1, int((y1 - y0) / downsample)))
    check_size(size, allow_large)
    region = slide.read_region((x0, y0), level, size).convert('RGB')
    image = cv2.cvtColor(np.array(region), cv2.COLOR_RGB2BGR)

    def to_local(x, y):
        return int((x - x0) / downsample), int((y - y0) / downsample)

    for polygon, _grade in entry['raw_ROI']:
        points = np.array([to_local(x, y) for x, y in polygon.exterior.coords], np.int32).reshape((-1, 1, 2))
        cv2.polylines(image, [points], isClosed=True, color=ROI_COLOR, thickness=roi_thickness)

    for patch_list, _grade, _id_roi in entry['covered_ROI']:
        for (patch_x, patch_y), _overlap_pct in patch_list:
            top_left = to_local(patch_x, patch_y)
            bottom_right = to_local(patch_x + patch_size, patch_y + patch_size)
            cv2.rectangle(image, top_left, bottom_right, PATCH_COLOR, patch_thickness)

    cv2.imwrite(output_path, image)
    return image.shape[1], image.shape[0]


def main():
    parser = argparse.ArgumentParser(description="Pathologist ROIs (red) and patches that cover them (blue) "
                                                 "from an already computed partition cache")
    parser.add_argument('wsi_path', help="WSI file (.tif/.tiff)")
    parser.add_argument('pkl_path', help="Cache wsi_patch_map_*.pkl generated by CSVTestListExtractor")
    parser.add_argument('output_path', help="Output PNG")
    parser.add_argument('--level', type=int, default=1, help="WSI layer in which it is read and drawn (default 1)")
    parser.add_argument('--padding', type=int, default=200,
                        help="Margin in layer 0 pixels around the ROIs: the larger the margin, the less zoom "
                             "and the more tissue visible around them (default 200)")
    parser.add_argument('--roi-thickness', type=int, default=2, help="Thickness of the red contour of the ROIs (default 2)")
    parser.add_argument('--patch-thickness', type=int, default=1, help="Thickness of the blue box of the patches (default 1)")
    parser.add_argument('--full', action='store_true',
                        help="Draws the whole image (complete layer 0) instead of cropping around the ROIs")
    parser.add_argument('--crop', type=int, nargs=4, metavar=('X0', 'Y0', 'X1', 'Y1'),
                        help="Manual crop in layer 0 coordinates (x0 y0 x1 y1), instead of cropping "
                             "around all the ROIs. Useful when the ROIs of the image form several "
                             "separate groups and only one of them is of interest")
    parser.add_argument('--allow-large', action='store_true',
                        help=f"Allows generating more than {MAX_PIXELS / 1e6:.0f} megapixels (it may take long and use a lot of memory/disk)")
    args = parser.parse_args()

    patch_size, _stride = parse_patch_size(args.pkl_path)
    entry = load_entry(args.pkl_path, args.wsi_path)
    if args.crop:
        crop_box = tuple(args.crop)
    elif args.full:
        width0, height0 = openslide.OpenSlide(args.wsi_path).dimensions
        crop_box = (0, 0, width0, height0)
    else:
        crop_box = roi_bounds(entry, args.padding)
    width, height = draw_overlay(args.wsi_path, entry, patch_size, args.level, crop_box, args.output_path,
                                 args.roi_thickness, args.patch_thickness, args.allow_large)
    print(f"{len(entry['raw_ROI'])} ROI, {entry['patch_number']} patches -> {args.output_path} "
          f"({width}x{height} px, layer {args.level})")


if __name__ == '__main__':
    main()
